import { test, expect } from '@playwright/test';
import { existsSync, mkdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { authorize, setEngineMode } from './helpers';

test.beforeEach(async ({ context }) => { await authorize(context); });

test('large recorded changes page files and diff lines without Git, retain counts and open current rename targets', async ({ page }) => {
  await page.goto('/chat/new');
  const createdResponse = page.waitForResponse((response) => response.url().endsWith('/api/v1/chats') && response.request().method() === 'POST');
  await page.getByRole('textbox', { name: '发送消息' }).fill('准备变更用例');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  const created = (await (await createdResponse).json()).data;
  await expect(page.getByText('收到：准备变更用例', { exact: true })).toBeVisible();
  expect(existsSync(join(created.chat.workspace, '.git'))).toBe(false);
  setEngineMode('changes', created.chat.workspace);
  await page.getByRole('textbox', { name: '发送消息' }).fill('批量编辑');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  await expect(page.getByRole('heading', { name: '批量变更完成', exact: true })).toBeVisible();
  const resources = page.getByRole('region', { name: '本轮资源' });
  await expect(resources.getByRole('button', { name: /153 个文件已更改/ })).toBeVisible();
  await expect(resources.getByRole('listitem')).toHaveCount(0);
  await resources.getByRole('button', { name: /153 个文件已更改/ }).click();
  await expect(resources.getByRole('listitem')).toHaveCount(100);
  await page.screenshot({ path: join(process.env.COBOT_E2E_ROOT!, 'filesystem-resources-expanded.png') });
  await resources.getByRole('button', { name: '审查 file-000.txt', exact: true }).click();
  const workspace = page.getByRole('tabpanel', { name: '工作区' });
  const history = workspace.getByRole('complementary', { name: '变更记录', exact: true });
  await expect(history.getByText(/^153 个已记录文件/)).toBeVisible();
  await history.getByRole('button').filter({ hasText: 'file-000.txt' }).click();
  await expect(history.getByText('+60000', { exact: true })).toBeVisible();
  await expect(workspace.getByText('此差异只保存了部分内容。', { exact: true })).toBeVisible();
  await expect(workspace.locator('pre').getByText('+line 00001', { exact: true })).toBeVisible();
  expect(await workspace.locator('pre > div').count()).toBeLessThanOrEqual(500);
  await workspace.getByRole('button', { name: '下一页', exact: true }).last().click();
  await expect(workspace.locator('pre').getByText('+line 00600', { exact: true })).toBeVisible();
  expect(await workspace.locator('pre > div').count()).toBeLessThanOrEqual(500);
  await page.screenshot({ path: join(process.env.COBOT_E2E_ROOT!, 'filesystem-changes-large.png') });

  await history.getByRole('button', { name: '下一页', exact: true }).click();
  await history.getByRole('button').filter({ hasText: 'file-149.txt' }).click();
  await expect(workspace.getByText('这部分差异未保存。', { exact: true })).toBeVisible();
  await workspace.getByRole('button', { name: '打开当前文件', exact: true }).click();
  await expect(workspace.getByText('content 149', { exact: true })).toBeVisible();
  await page.getByRole('tab', { name: '变更', exact: true }).click();
  await history.getByRole('button', { name: '下一页', exact: true }).click();
  await history.getByRole('button').filter({ hasText: 'renamed.txt' }).click();
  await expect(workspace.locator('pre').getByText('rename to renamed.txt', { exact: true })).toBeVisible();
  await workspace.getByRole('button', { name: '打开当前文件', exact: true }).click();
  await expect(workspace.getByText('renamed fixture', { exact: true })).toBeVisible();
  await page.getByRole('tab', { name: '变更', exact: true }).click();
  await history.getByRole('button').filter({ hasText: 'deleted.txt' }).click();
  await expect(workspace.locator('pre').getByText('-removed', { exact: true })).toBeVisible();
  const tabs = await page.getByRole('tablist', { name: '工作区' }).getByRole('tab').count();
  await workspace.getByRole('button', { name: '打开当前文件', exact: true }).click();
  await expect(workspace.getByText('此文件已不存在', { exact: true })).toBeVisible();
  await expect(workspace.locator('pre').getByText('-removed', { exact: true })).toBeVisible();
  await expect(page.getByRole('tablist', { name: '工作区' }).getByRole('tab')).toHaveCount(tabs);
  await expect(history.getByRole('listitem').filter({ hasText: 'binary.dat' }).getByText('统计未知', { exact: true })).toBeVisible();
});


test('reply resources confirm existing files, deduplicate aliases and open the same file tab', async ({ page }) => {
  await page.goto('/chat/new');
  const response = page.waitForResponse((item) => item.url().endsWith('/api/v1/chats') && item.request().method() === 'POST');
  await page.getByRole('textbox', { name: '发送消息' }).fill('resource setup');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  const created = (await (await response).json()).data;
  await expect(page.getByText('收到：resource setup', { exact: true })).toBeVisible();
  await expect(page.getByRole('region', { name: '本轮资源' })).toHaveCount(0);
  setEngineMode('resources', created.chat.workspace);
  await page.getByRole('textbox', { name: '发送消息' }).fill('show resources');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Resources ready' })).toBeVisible();
  const resources = page.getByRole('region', { name: '本轮资源' });
  await expect(resources.getByRole('listitem')).toHaveCount(3);
  await expect(resources.getByText('missing.md', { exact: true })).toHaveCount(0);
  await expect(resources.getByRole('link', { name: '打开', exact: true }).first()).toHaveAttribute('href', 'http://localhost:3000/');
  await resources.getByRole('button', { name: '打开 artifact.md', exact: true }).click();
  const workspace = page.getByRole('tabpanel', { name: '工作区' });
  await expect(workspace.getByRole('heading', { name: 'Artifact preview' })).toBeVisible();
  await resources.getByRole('button', { name: '打开 artifact.md', exact: true }).click();
  await expect(page.getByRole('tab', { name: 'artifact.md', exact: true })).toHaveCount(1);
  await page.screenshot({ path: join(process.env.COBOT_E2E_ROOT!, 'filesystem-resources-files.png') });
});

test('team reply resources retain scope, reuse tabs and survive narrow and dark layouts', async ({ page }) => {
  const directory = join(process.env.COBOT_E2E_ROOT!, 'team-resources-' + Date.now());
  mkdirSync(directory, { recursive: true });
  setEngineMode('resources', directory);
  await page.goto('/chat/new');
  await page.getByRole('radio', { name: '团队', exact: true }).click();
  await page.getByRole('button', { name: /新建团队|create team/i }).first().click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel(/团队名称|team name/i).fill('资源验收团队');
  await dialog.getByLabel(/工作目录|directory/i).fill(directory);
  const createdResponse = page.waitForResponse((response) => response.url().endsWith('/api/v1/teams') && response.request().method() === 'POST');
  await dialog.getByRole('button', { name: /创建|create/i }).click();
  const created = (await (await createdResponse).json()).data;
  const leaders = page.getByRole('button', { name: /项目经理/ }).filter({ visible: true });
  await expect(leaders).toHaveCount(1, { timeout: 15000 });
  await leaders.first().click();
  await page.locator('textarea').first().fill('show team resources');
  await page.locator('textarea').first().press('Enter');
  await expect(page.getByRole('heading', { name: 'Resources ready', exact: true })).toBeVisible({ timeout: 15000 });
  const resources = page.getByRole('region', { name: '本轮资源' });
  await expect(resources.getByRole('listitem')).toHaveCount(3);
  await page.getByRole('button', { name: '创建标签页', exact: true }).click();
  await page.getByRole('button', { name: /文件 浏览当前工作区的文件/ }).click();
  await page.getByRole('button', { name: '收起工作区', exact: true }).click();
  const opened = page.waitForResponse((response) => { const url = new URL(response.url()); return url.pathname === `/api/v1/workspaces/team/${created.team.id}/file` && url.searchParams.get('path') === 'artifact.md'; });
  await resources.getByRole('button', { name: '打开 artifact.md', exact: true }).click();
  expect((await (await opened).json()).data.path).toBe('artifact.md');
  const workspace = page.getByRole('tabpanel', { name: '工作区' });
  await expect(workspace.getByRole('heading', { name: 'Artifact preview', exact: true })).toBeVisible();
  await resources.getByRole('button', { name: '打开 artifact.md', exact: true }).click();
  await expect(page.getByRole('tab', { name: 'artifact.md', exact: true })).toHaveCount(1);
  await page.locator('html').evaluate((element) => { element.dataset.mode = 'dark'; element.style.colorScheme = 'dark'; });
  await expect(resources.getByRole('button', { name: '打开 artifact.md', exact: true })).toHaveCSS('color', 'rgb(225, 223, 217)');
  await page.screenshot({ path: join(process.env.COBOT_E2E_ROOT!, 'filesystem-resources-team-dark.png') });
  await page.setViewportSize({ width: 760, height: 900 });
  await page.getByRole('button', { name: '收起工作区', exact: true }).click();
  await expect(resources.getByRole('button', { name: '打开 artifact.md', exact: true })).toBeVisible();
  await resources.getByRole('button', { name: '打开 artifact.md', exact: true }).click();
  await expect(workspace.getByRole('heading', { name: 'Artifact preview', exact: true })).toBeVisible();
  await page.screenshot({ path: join(process.env.COBOT_E2E_ROOT!, 'filesystem-resources-team-narrow.png') });
  await page.getByRole('button', { name: '收起工作区', exact: true }).click();
  unlinkSync(join(directory, 'artifact.md'));
  await resources.getByRole('button', { name: '打开 artifact.md', exact: true }).click();
  await expect(resources.getByText('此文件已不存在', { exact: true })).toBeVisible();
  writeFileSync(join(directory, 'artifact.md'), '# Artifact preview\n');
  await resources.getByRole('button', { name: '打开 artifact.md', exact: true }).click();
  await expect(workspace.getByRole('heading', { name: 'Artifact preview', exact: true })).toBeVisible();
  await expect(page.getByRole('tab', { name: 'artifact.md', exact: true })).toHaveCount(1);
});
