import { test, expect } from '@playwright/test';
import * as P from '../../../frontend/node_modules/@office-kit/pptx/dist/index.js';
import { truncateSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { authorize, selectWorkspaceFile } from './helpers';
test.beforeEach(async ({ context }) => { await authorize(context); });
test('PPTX renders slide layout and images, navigates its slide list and zooms', async ({ page }) => {
  await page.goto('/chat/new');
  const response = page.waitForResponse((item) => item.url().endsWith('/api/v1/chats') && item.request().method() === 'POST');
  await page.getByRole('textbox', { name: '发送消息' }).fill('presentation setup');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  const created = (await (await response).json()).data;
  await expect(page.getByText('收到：presentation setup', { exact: true })).toBeVisible();
  const presentation = P.createPresentation({ size: '16:9' });
  const layout = P.getSlideLayouts(presentation)[0];
  const first = P.addSlide(presentation, { layout });
  P.addSlideTextBox(first, { x: 914400, y: 914400, w: 7000000, h: 1200000, text: 'Presentation title 中文' });
  const shape = P.addSlideShape(first, { preset: 'roundRect', x: 914400, y: 2600000, w: 2500000, h: 1300000, text: 'Blue shape' });
  P.setShapeFill(shape, '#dcecff');
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aZk8AAAAASUVORK5CYII=', 'base64');
  P.addSlideImage(first, png, { x: 6000000, y: 2600000, w: 914400, h: 914400, format: 'png' });
  const second = P.addSlide(presentation, { layout });
  P.addSlideTextBox(second, { x: 914400, y: 914400, w: 7000000, h: 1200000, text: 'Second slide fixture' });
  writeFileSync(join(created.chat.workspace, 'slides.pptx'), await P.savePresentation(presentation));
  writeFileSync(join(created.chat.workspace, 'damaged.pptx'), 'bad zip');
  writeFileSync(join(created.chat.workspace, 'empty.pptx'), '');
  const blank = P.createPresentation({ size: '16:9' });
  writeFileSync(join(created.chat.workspace, 'blank.pptx'), await P.savePresentation(blank));
  for (let index = 0; index < 200; index++) P.addSlide(blank, { layout: P.getSlideLayouts(blank)[0] });
  writeFileSync(join(created.chat.workspace, 'max-slides.pptx'), await P.savePresentation(blank));
  P.addSlide(blank, { layout: P.getSlideLayouts(blank)[0] });
  writeFileSync(join(created.chat.workspace, 'too-many-slides.pptx'), await P.savePresentation(blank));
  const oversized = join(created.chat.workspace, 'oversized.pptx');
  writeFileSync(oversized, ''); truncateSync(oversized, 11 * 1024 * 1024);
  const content: string[] = [];
  page.on('request', (request) => { const url = new URL(request.url()); if (url.pathname.endsWith('/content')) content.push(url.searchParams.get('path') ?? ''); });

  await page.getByRole('button', { name: '创建标签页', exact: true }).click();
  await page.getByRole('button', { name: /文件 浏览当前工作区的文件/ }).click();
  await selectWorkspaceFile(page, 'slides.pptx');
  const workspace = page.getByRole('tabpanel', { name: '工作区' });
  const firstFrame = page.frameLocator('iframe[title="第 1 张幻灯片"]');
  await expect(firstFrame.getByText('Presentation title 中文', { exact: true })).toBeVisible();
  await expect(firstFrame.getByText('Blue shape', { exact: true })).toBeVisible();
  await expect(firstFrame.locator('image')).toHaveCount(1);
  await expect(page.locator('iframe[title="第 1 张幻灯片"]')).toHaveAttribute('sandbox', '');
  await workspace.getByRole('button', { name: '下一页', exact: true }).click();
  await expect(page.frameLocator('iframe[title="第 2 张幻灯片"]').getByText('Second slide fixture', { exact: true })).toBeVisible();
  await workspace.getByRole('combobox', { name: '幻灯片', exact: true }).click();
  await page.getByRole('option', { name: /^1 \/ 2/ }).click();
  await expect(firstFrame.getByText('Presentation title 中文', { exact: true })).toBeVisible();
  await workspace.getByRole('button', { name: '100%', exact: true }).click();
  await expect(page.locator('iframe[title="第 1 张幻灯片"]')).toHaveCSS('width', '1280px');
  await workspace.getByRole('button', { name: '缩小', exact: true }).click();
  await expect(page.locator('iframe[title="第 1 张幻灯片"]')).toHaveCSS('width', '1024px');
  await workspace.getByRole('button', { name: '适应窗口', exact: true }).click();
  await expect.poll(() => page.locator('iframe[title="第 1 张幻灯片"]').evaluate((element) => element.getBoundingClientRect().width)).toBeLessThan(500);
  await page.screenshot({ path: join(process.env.COBOT_E2E_ROOT!, 'filesystem-pptx.png') });
  await selectWorkspaceFile(page, 'damaged.pptx');
  await expect(workspace.getByText('此演示文稿已损坏、已加密或不受支持。', { exact: true })).toBeVisible();
  await selectWorkspaceFile(page, 'empty.pptx');
  await expect(workspace.getByText('此演示文稿已损坏、已加密或不受支持。', { exact: true })).toBeVisible();
  await selectWorkspaceFile(page, 'blank.pptx');
  await expect(workspace.getByText('此演示文稿没有幻灯片。', { exact: true })).toBeVisible();
  await selectWorkspaceFile(page, 'max-slides.pptx');
  await expect(workspace.getByRole('combobox', { name: '幻灯片', exact: true })).toContainText('1 / 200');
  await workspace.getByRole('combobox', { name: '幻灯片', exact: true }).click();
  await page.getByRole('option', { name: '200 / 200', exact: true }).click();
  await expect(page.locator('iframe[title="第 200 张幻灯片"]')).toBeVisible();
  await selectWorkspaceFile(page, 'too-many-slides.pptx');
  await expect(workspace.getByText('此演示文稿超过预览上限。', { exact: true })).toBeVisible();
  await selectWorkspaceFile(page, 'oversized.pptx');
  await expect(workspace.getByText('此文件超过 10 MiB 预览上限，可用系统打开。', { exact: true })).toBeVisible();
  expect(content).not.toContain('oversized.pptx');

});
