import { test, expect } from '@playwright/test';
import { mkdirSync, symlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { authorize } from './helpers';
test.beforeEach(async ({ context }) => { await authorize(context); });
test('directory aliases retain independent tree identities and ancestor links stop recursion', async ({ page }) => {
  test.skip(process.platform === 'win32', 'Requires symlink privileges; native Windows alias validation is separate.');
  await page.goto('/chat/new');
  const response = page.waitForResponse((item) => item.url().endsWith('/api/v1/chats') && item.request().method() === 'POST');
  await page.getByRole('textbox', { name: '发送消息' }).fill('alias setup');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  const created = (await (await response).json()).data;
  await expect(page.getByText('收到：alias setup', { exact: true })).toBeVisible();
  const root = created.chat.workspace;
  mkdirSync(join(root, 'docs'));
  writeFileSync(join(root, 'docs', 'note.md'), '# Alias target fixture\n');
  symlinkSync(join(root, 'docs'), join(root, 'linked'));
  symlinkSync(root, join(root, 'docs', 'up'));
  symlinkSync(join(root, 'docs', 'note.md'), join(root, 'shortcut.md'));
  const errors: string[] = []; page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
  await page.getByRole('button', { name: '创建标签页', exact: true }).click();
  await page.getByRole('button', { name: /文件 浏览当前工作区的文件/ }).click();
  const workspace = page.getByRole('tabpanel', { name: '工作区' });
  const tree = workspace.getByRole('tree', { name: '项目文件' });
  await tree.getByRole('treeitem', { name: 'docs', exact: true }).click();
  await tree.getByRole('treeitem', { name: 'linked', exact: true }).click();
  const linked = tree.locator('[role="treeitem"][aria-level="1"]').filter({ hasText: /^linked/ });
  await expect(linked.getByRole('treeitem', { name: 'note.md', exact: true })).toBeVisible();
  await expect(tree.getByRole('treeitem', { name: 'note.md', exact: true })).toHaveCount(2);
  await linked.getByRole('treeitem', { name: 'up', exact: true }).click();
  await expect(linked.getByText('此目录指向已显示的上级目录。', { exact: true })).toBeVisible();
  await expect(tree.getByRole('treeitem')).toHaveCount(8);
  await linked.getByRole('treeitem', { name: 'note.md', exact: true }).click();
  await expect(workspace.getByRole('heading', { name: 'Alias target fixture' })).toBeVisible();
  await expect(workspace.getByText('docs/note.md', { exact: true })).toBeVisible();
  await tree.getByRole('treeitem', { name: 'shortcut.md', exact: true }).click();
  await expect(workspace.getByRole('heading', { name: 'Alias target fixture' })).toBeVisible();
  expect(errors.filter((error) => /same key|duplicate|Maximum update depth/.test(error))).toEqual([]);
  await page.reload();
  await expect(linked.getByText('此目录指向已显示的上级目录。', { exact: true })).toBeVisible();
  await page.screenshot({ path: join(process.env.COBOT_E2E_ROOT!, 'filesystem-aliases.png') });
});


test('restored current file remains visible when its directory is beyond the first page', async ({ page }) => {
  await page.goto('/chat/new');
  const response = page.waitForResponse((item) => item.url().endsWith('/api/v1/chats') && item.request().method() === 'POST');
  await page.getByRole('textbox', { name: '发送消息' }).fill('paged tree setup');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  const created = (await (await response).json()).data;
  await expect(page.getByText('收到：paged tree setup', { exact: true })).toBeVisible();
  for (let index = 0; index < 205; index++) mkdirSync(join(created.chat.workspace, 'folder-' + String(index).padStart(3, '0')));
  mkdirSync(join(created.chat.workspace, 'z-outside'));
  writeFileSync(join(created.chat.workspace, 'z-outside', 'note.md'), '# Beyond first page fixture\n');
  const key = 'cobot.workspace.v1.chat:' + created.chat.id;
  await page.evaluate(({ key }) => {
    localStorage.setItem(key, JSON.stringify({ open: true, width: 640, tabs: [{ id: 'file:restored', kind: 'file', title: 'note.md', ref: 'z-outside/note.md', fileView: {} }], activeId: 'file:restored' }));
  }, { key });
  await page.reload();
  const workspace = page.getByRole('tabpanel', { name: '工作区' });
  await expect(workspace.getByRole('heading', { name: 'Beyond first page fixture' })).toBeVisible();
  const tree = workspace.getByRole('tree', { name: '项目文件' });
  await expect(tree.getByRole('treeitem', { name: 'note.md', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(tree.getByRole('treeitem', { name: 'note.md', exact: true })).toBeInViewport();
  await expect(tree.getByRole('treeitem', { name: '加载更多', exact: true })).toHaveCount(1);
  expect(await tree.getByRole('treeitem').count()).toBeLessThanOrEqual(203);
  await tree.getByRole('treeitem', { name: '加载更多', exact: true }).click();
  await expect(tree.getByRole('treeitem', { name: '加载更多', exact: true })).toHaveCount(0);
  await expect(tree.getByRole('treeitem', { name: 'note.md', exact: true })).toHaveCount(1);
  await expect(tree.getByRole('treeitem', { name: 'note.md', exact: true })).toBeInViewport();
  await page.screenshot({ path: join(process.env.COBOT_E2E_ROOT!, 'filesystem-tree-restored.png') });
});
